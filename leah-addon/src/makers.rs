/// The maker's name for a CV 8 value, when the NMRA has assigned it.
pub fn maker_name(id: u8) -> Option<&'static str> {
    MAKERS.binary_search_by_key(&id, |(n, _)| *n).ok().map(|i| MAKERS[i].1)
}

/// A maker's product family from CV 7, where the maker's own documents say what CV 7 means:
/// SoundTraxx's "product identification" guide (rev. F, 2025-09).
pub fn family_name(maker: u8, version: u8) -> Option<&'static str> {
    if maker != 141 {
        return None;
    }
    Some(match version {
        64 => "Tsunami",
        65 => "MC1",
        66 => "MC2",
        68 => "Crummy Light",
        69 => "SoundCar",
        70 => "Econami",
        71 => "Tsunami2",
        72 => "Blunami",
        80 => "OEM Tsunami",
        81 => "OEM MC1",
        82 => "Sound Value, RTR, Mainline",
        83 => "TSX (two-piece sound decoder)",
        84 => "Piko Sound System",
        85 => "OEM SoundCar",
        86 => "Bachmann Large Scale Thomas",
        _ => return None,
    })
}

/// The kind of sound in a SoundTraxx Tsunami2, Econami, or Blunami (CV 254).
pub fn soundtraxx_sound(value: i64) -> Option<&'static str> {
    Some(match value {
        1 => "steam",
        2 => "diesel",
        3 => "electric",
        5 => "UK steam",
        6 => "UK diesel",
        _ => return None,
    })
}

#[cfg(test)]
mod tests {
    #[test]
    fn the_nmras_ids() {
        assert_eq!(super::maker_name(141), Some("Throttle-Up (Soundtraxx)"));
        assert_eq!(super::maker_name(151), Some("Electronic Solutions Ulm GmbH"));
        assert_eq!(super::maker_name(153), Some("Train Control Systems"));
        assert_eq!(super::maker_name(13), Some("Public Domain & Do-It-Yourself Decoders"));
        assert_eq!(super::maker_name(11), Some("NCE Corporation (formerly North Coast Engineering)"));
        // (Every name whole: no wrapped line left in the table.)
        assert!(super::MAKERS.iter().all(|(_, n)| n.matches('(').count() == n.matches(')').count()));
        assert!(super::MAKERS.windows(2).all(|w| w[0].0 < w[1].0));
    }
}
